USE agri_traceability;

-- ============================================================
-- 一、新建表
-- ============================================================

-- 1. 时令关联表
CREATE TABLE IF NOT EXISTS product_seasonal (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    product_id BIGINT NOT NULL COMMENT '商品ID',
    month TINYINT NOT NULL COMMENT '月份1-12',
    is_peak TINYINT DEFAULT 0 COMMENT '是否旺季 0否1是',
    description VARCHAR(200) COMMENT '时令说明',
    UNIQUE KEY uk_product_month (product_id, month)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品时令关联';

-- 2. 农业百科文章表
CREATE TABLE IF NOT EXISTS knowledge_article (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    title VARCHAR(100) NOT NULL COMMENT '标题',
    summary VARCHAR(200) COMMENT '摘要',
    content TEXT NOT NULL COMMENT '正文(Markdown)',
    cover_image VARCHAR(500) COMMENT '封面图',
    category VARCHAR(20) NOT NULL COMMENT 'SELECTION选购/NUTRITION营养/STORAGE储存/USAGE食用/GENERAL常识',
    tags VARCHAR(200) COMMENT '标签逗号分隔',
    view_count INT DEFAULT 0 COMMENT '阅读量',
    sort INT DEFAULT 0 COMMENT '排序',
    status TINYINT DEFAULT 1 COMMENT '1发布0草稿',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='农业百科文章';

-- 3. 食谱表
CREATE TABLE IF NOT EXISTS recipe (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    title VARCHAR(100) NOT NULL COMMENT '标题',
    description VARCHAR(500) COMMENT '简介',
    cover_image VARCHAR(500) COMMENT '成品图',
    cook_time INT COMMENT '烹饪时长(分钟)',
    servings INT COMMENT '份数',
    difficulty VARCHAR(10) COMMENT 'SIMPLE/EASY/NORMAL/HARD',
    steps TEXT COMMENT '步骤JSON',
    category VARCHAR(20) COMMENT 'DESSERT甜品/STAPLE主食/SOUP汤品/SIDE小菜/JUICE果汁',
    view_count INT DEFAULT 0,
    status TINYINT DEFAULT 1,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='农产食谱';

-- 4. 食谱-商品关联表
CREATE TABLE IF NOT EXISTS recipe_product (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    recipe_id BIGINT NOT NULL COMMENT '食谱ID',
    product_id BIGINT NOT NULL COMMENT '商品ID',
    amount VARCHAR(50) COMMENT '用量如200g/1个',
    is_main_ingredient TINYINT DEFAULT 0 COMMENT '是否主料',
    UNIQUE KEY uk_recipe_product (recipe_id, product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='食谱食材关联';

-- 5. FAQ常见问题表
CREATE TABLE IF NOT EXISTS faq (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    category VARCHAR(20) NOT NULL COMMENT 'ORDER/PAYMENT/SHIPPING/TRACE/AFTER_SALE/ACCOUNT',
    question VARCHAR(200) NOT NULL,
    answer TEXT NOT NULL,
    view_count INT DEFAULT 0,
    sort INT DEFAULT 0,
    status TINYINT DEFAULT 1,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='常见问题';

